#!/usr/bin/env python3
"""
render_n1_rollup.py - render analysis/compat/n1-action-rollup.md from the
JSON, so the prose never drifts from the numbers.

Same discipline as tools/render_master_list.py: the JSON is the source, the
markdown is generated. Edit the JSON (or re-run tools/n1_rollup.py), never
the markdown.

    py tools/render_n1_rollup.py
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEF_IN = os.path.join(ROOT, "analysis", "compat", "n1-action-rollup.json")
DEF_OUT = os.path.join(ROOT, "analysis", "compat", "n1-action-rollup.md")

CLASSES = ("REWRITE_REQUIRED", "NO_ACTION_NOP", "NO_ACTION_HOST_HAS_IT",
           "PROTOCOL_UNDEFINED", "UNADJUDICATED")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inp", default=DEF_IN)
    ap.add_argument("--out", default=DEF_OUT)
    args = ap.parse_args()

    with open(args.inp, encoding="utf-8") as fh:
        d = json.load(fh)
    h = d["target_host_class"]
    L = []
    w = L.append

    w("# 25G83 vma2 on Arm Neoverse N1: how many words have to change")
    w("")
    w(f"Generated from `{os.path.relpath(args.inp, ROOT)}` by "
      f"`tools/render_n1_rollup.py`. Do not edit this file; edit the JSON or "
      f"re-run `tools/n1_rollup.py`.")
    w("")
    w("The sweep counts distance from `armmac-generic-v1`, which stops at")
    w("ARMv8.2-A and promises only FP, AdvSIMD, FEAT_LSE and FEAT_TGran16.")
    w("That is the right baseline for a portability claim and the wrong one")
    w("for a work estimate, in both directions at once: a real Neoverse N1")
    w("implements more than the promise, and some of what it does NOT")
    w("implement still costs nothing.")
    w("")
    w("## 1 Target")
    w("")
    w(f"- core: **{h['core']}**, {h['isa']}")
    w("- first-class shapes: " + ", ".join(h["first_class_shapes"]))
    w("- host-profile keys used: " + ", ".join(f"`{k}`" for k in h["profile_keys_used"]))
    w("- development/CI test bed: " + ", ".join(f"`{k}`" for k in h["testbed_keys"]))
    w("- absent, and that is what drives the work: "
      + ", ".join(f"`{k}`" for k in h["absent_features_that_drive_the_work"]))
    w("- present, and that is what removes work: "
      + ", ".join(f"`{k}`" for k in h["present_features_that_remove_work"]))
    w("")
    for k, v in (h.get("shapes_without_a_profile_entry") or {}).items():
        w(f"**`{k}`**: {v}")
        w("")
    if h.get("kvm_caveat"):
        w(f"**KVM caveat.** {h['kvm_caveat']}")
        w("")

    w("## 2 Action classes")
    w("")
    w("| class | meaning |")
    w("| :-- | :-- |")
    for k, v in d["action_class_docs"].items():
        w(f"| `{k}` | {v} |")
    w("")
    w("Two rules in the apportionment point in opposite directions and both")
    w("have to be stated, because getting either one wrong moves the headline")
    w("number by hundreds of thousands of instructions:")
    w("")
    w("- **PAC is split.** Its HINT half executes as a NOP and needs nothing;")
    w("  its register and branch half is UNDEFINED and needs all of it.")
    w("- **BTI needs nothing even though N1 lacks it**, for the same")
    w("  HINT-space reason. An apportionment driven purely off host support")
    w("  tables gets this backwards.")
    w("")

    w("## 3 Roll-up")
    w("")
    w("| scope | " + " | ".join(c.replace("NO_ACTION_", "") for c in CLASSES)
      + " | strong coverage | apportionment |")
    w("| :-- | " + " | ".join("--:" for _ in CLASSES) + " | --: | :-- |")
    for s in d["scopes"]:
        if not s.get("present"):
            w(f"| `{s['scope']}` | " + " | ".join("—" for _ in CLASSES)
              + " | — | ABSENT |")
            continue
        a = s["actions"]
        ci = s["confidence_indicators"]
        ok = "exact" if s["apportionment_complete"] else \
             f"**INCOMPLETE ({s['apportionment_delta']:+,})**"
        w(f"| `{s['scope']}` | " + " | ".join(f"{a[c]:,}" for c in CLASSES)
          + f" | {ci['strong_coverage_pct']}% | {ok} |")
    g = d["grand_total"]
    w("| **total** | " + " | ".join(f"**{g[c]:,}**" for c in CLASSES)
      + " | | |")
    w("")
    w(f"**{g['REWRITE_REQUIRED']:,}** words have to change. "
      f"**{g['NO_ACTION_NOP']:,}** findings need nothing done to them because "
      f"they are HINT-space PAC and BTI. "
      f"**{g['NO_ACTION_HOST_HAS_IT']:,}** are above the baseline promise but "
      f"present on every first-class host.")
    w("")
    if d.get("scopes_with_incomplete_apportionment"):
        w("**Incomplete apportionment in: "
          + ", ".join(d["scopes_with_incomplete_apportionment"])
          + "** — the class totals for those scopes do not sum to the sweep's "
            "own findings_total, so their rows are not usable.")
        w("")

    w("## 4 Confidence")
    w("")
    w("A count of words to rewrite is only as good as the proportion of those")
    w("words that are really instructions. These are the same indicators the")
    w("master list's evidence grades turn on.")
    w("")
    w("| scope | executable bytes | strong | weak | failing | proven data | "
      "unreachable findings | adjacent to data |")
    w("| :-- | --: | --: | --: | --: | --: | --: | --: |")
    for s in d["scopes"]:
        if not s.get("present"):
            continue
        ci = s["confidence_indicators"]
        pd = ci.get("proven_data_bytes") or 0
        eb = ci.get("executable_bytes") or 0
        w(f"| `{s['scope']}` | {eb:,} | {ci['strong_coverage_pct']}% | "
          f"{(ci.get('bytes_with_weak_evidence') or 0):,} | "
          f"{(ci.get('bytes_with_failing_state') or 0):,} | "
          f"{pd:,} ({100.0 * pd / eb:.2f}%) | "
          f"{(ci.get('findings_unreachable') or 0):,} | "
          f"{(ci.get('findings_adjacent_to_data') or 0):,} |")
    w("")

    w("## 5 Per-scope apportionment, row by row")
    w("")
    w("Every row names the feature or category, the class, the count and the")
    w("reason. A reader who disagrees with a single class assignment can find")
    w("exactly which row to argue with.")
    for s in d["scopes"]:
        if not s.get("present"):
            continue
        w("")
        w(f"### 5.x `{s['scope']}`  "
          f"({s['findings_apportioned']:,} of "
          f"{s['findings_total_reported_by_sweep']:,} apportioned)")
        w("")
        w("| class | findings | feature or category | reason |")
        w("| :-- | --: | :-- | :-- |")
        for r in s["rows"]:
            what = r.get("feature") or r.get("category") or ""
            w(f"| `{r['action']}` | {r.get('findings', 0):,} | "
              f"`{what}` | {r['reason']} |")
    w("")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"[+] wrote {args.out} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
